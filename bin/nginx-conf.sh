#!/usr/bin/env bash
# Prints an nginx server block for this app, using wherever the app is installed.
#
# Usage: bin/nginx-conf.sh <server_name> [mount_path] [--http]
#   server_name  e.g. relay.example.com
#   mount_path   URL prefix to serve under, e.g. /relay (default: site root)
#   --http       plain HTTP only (local testing or behind a TLS-terminating proxy)
#
# Env overrides: PHP_FPM (socket, e.g. unix:/run/php/php8.5-fpm.sock or 127.0.0.1:9000),
#                SSL_CERT, SSL_KEY (default: Let's Encrypt paths for server_name),
#                MAX_BODY (default 40m; keep in line with PHP post_max_size).
#
# Example: bin/nginx-conf.sh relay.example.com | sudo tee /etc/nginx/sites-available/relay
set -euo pipefail

http_only=0
args=()
for a in "$@"; do
    case "$a" in
        --http) http_only=1 ;;
        -h|--help) sed -n '2,13p' "$0" | sed 's/^# \{0,1\}//'; exit 0 ;;
        *) args+=("$a") ;;
    esac
done
server_name=${args[0]:-}
mount=${args[1]:-/}
if [ -z "$server_name" ]; then
    echo "usage: $0 <server_name> [mount_path] [--http]" >&2
    exit 1
fi

app_root=$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd -P)

# Normalise mount path to "/" or "/prefix/".
mount="/${mount#/}"
mount="${mount%/}/"
script_name="${mount}index.php"

if [ -z "${PHP_FPM:-}" ]; then
    sock=$(ls -1 /run/php/php*-fpm.sock 2>/dev/null | sort -V | tail -1 || true)
    if [ -n "$sock" ]; then
        PHP_FPM="unix:$sock"
    else
        PHP_FPM="unix:/run/php/php-fpm.sock"
        echo "warning: no PHP-FPM socket found in /run/php; using $PHP_FPM (install php-fpm or set PHP_FPM)" >&2
    fi
fi
SSL_CERT=${SSL_CERT:-/etc/letsencrypt/live/$server_name/fullchain.pem}
SSL_KEY=${SSL_KEY:-/etc/letsencrypt/live/$server_name/privkey.pem}
MAX_BODY=${MAX_BODY:-40m}

if [ "$mount" = "/" ]; then
    location="location /"
else
    location="location ^~ $mount"
fi

if [ "$http_only" = 1 ]; then
    listen="    listen 80;"
else
    listen="    listen 443 ssl;
    http2 on;
    ssl_certificate     $SSL_CERT;
    ssl_certificate_key $SSL_KEY;"
fi

cat <<EOF
# Generated by bin/nginx-conf.sh for $app_root
server {
$listen
    server_name $server_name;

    # Reference-image uploads: keep in line with PHP's post_max_size.
    client_max_body_size $MAX_BODY;

    # Front controller: every request goes to index.php, nothing is served
    # from disk, so config.php, storage/, bin/ and dotfiles are never exposed.
    $location {
        include fastcgi_params;   # passes the Authorization header as HTTP_AUTHORIZATION
        fastcgi_param SCRIPT_FILENAME $app_root/index.php;
        fastcgi_param SCRIPT_NAME     $script_name;
        fastcgi_pass $PHP_FPM;

        # Up to n=4 sequential OpenRouter calls at 120 s each.
        fastcgi_read_timeout 500s;
        fastcgi_send_timeout 120s;
    }
}
EOF

if [ "$http_only" = 0 ]; then
    cat <<EOF

server {
    listen 80;
    server_name $server_name;
    return 301 https://\$host\$request_uri;
}
EOF
fi
